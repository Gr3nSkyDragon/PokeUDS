def exp_for_level(growth: int, n: int) -> int:
    """Experience needed for level n (pokecrystal CalcExpAtLevel; the same curves through Gen 7)."""
    if n <= 1:
        return 0
    if growth == 0:
        return n ** 3
    if growth == 1:          # Erratic
        if n <= 50:
            return n ** 3 * (100 - n) // 50
        if n <= 68:
            return n ** 3 * (150 - n) // 100
        if n <= 98:
            return n ** 3 * ((1911 - 10 * n) // 3) // 500
        return n ** 3 * (160 - n) // 100
    if growth == 2:          # Fluctuating
        if n <= 15:
            return n ** 3 * ((n + 1) // 3 + 24) // 50
        if n <= 36:
            return n ** 3 * (n + 14) // 50
        return n ** 3 * (n // 2 + 32) // 50
    if growth == 3:
        return 6 * n ** 3 // 5 - 15 * n ** 2 + 100 * n - 140
    if growth == 4:
        return 4 * n ** 3 // 5
    return 5 * n ** 3 // 4


def level_for_exp(dex: int, exp: int) -> int:
    growth = GROWTH[dex] if 0 < dex < len(GROWTH) else 0
    level = 1
    while level < 100 and exp >= exp_for_level(growth, level + 1):
        level += 1
    return level
