"""Generate pokeuds/vc/gbdata.py from pret/pokecrystal and pret/pokered checkouts.

    python scripts/gen_gb_tables.py /path/to/pokecrystal /path/to/pokered

Everything the Game Boy trade engines need from the games' data, taken from pret's sources:
the Gen 1 species index order (pokered ``data/pokemon/dex_order.asm``, MissingNo as 0), base stats and types
(``data/pokemon/base_stats/*.asm``), the Red/Blue base Special (``gen1_base_special.asm``), the
Time Capsule catch-rate items (``data/items/catch_rate_items.asm``) and the character map.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path


def consts(path: Path, start: int = 0, stop: str | None = None) -> dict[str, int]:
    """Values of `const` names in a pret constants file (const_def, const_skip, const_next), up to `stop`."""
    values: dict[str, int] = {}
    value = start
    for raw in path.read_text().splitlines():
        if stop and stop in raw:
            break
        line = raw.split(";", 1)[0].strip()
        if m := re.match(r"const_def\s*(\S+)?", line):
            value = int(m.group(1).replace("$", "0x"), 0) if m.group(1) else 0
        elif m := re.match(r"const_next\s+(\S+)", line):
            value = int(m.group(1).replace("$", "0x"), 0)
        elif line.startswith("const_skip"):
            value += 1
        elif m := re.match(r"const\s+(\w+)", line):
            values.setdefault(m.group(1), value)
            value += 1
    return values


def commented_consts(path: Path) -> dict[str, int]:
    """`const NAME ; xx` with the value from the hex comment (the item file's TM macros also count)."""
    return {m.group(1): int(m.group(2), 16)
            for m in re.finditer(r"const\s+(\w+)\s*;\s*([0-9a-fA-F]{2})\b", path.read_text())}


def main(root: Path, red: Path, out: Path) -> None:
    species = consts(root / "constants/pokemon_constants.asm", stop="NUM_POKEMON")   # not the Unown letters after it
    species = {k: v for k, v in species.items() if 1 <= v <= 251}
    types = consts(root / "constants/type_constants.asm")
    items = commented_consts(root / "constants/item_constants.asm")
    by_value = {v: k for k, v in species.items()}

    dex = consts(red / "constants/pokedex_constants.asm")
    gen1_order = []
    for raw in (red / "data/pokemon/dex_order.asm").read_text().splitlines():
        line = raw.split(";", 1)[0].strip()
        if m := re.match(r"db\s+(\w+)", line):
            gen1_order.append(dex.get(m.group(1), 0))   # "db 0" is a MissingNo slot.
    assert len(gen1_order) == 190 and sorted(set(gen1_order) - {0}) == list(range(1, 152))

    specials = [int(m.group(1)) for m in re.finditer(r"db\s+(\d+)\s*;",
                (root / "data/pokemon/gen1_base_special.asm").read_text())]

    base = {}
    for f in sorted((root / "data/pokemon/base_stats").glob("*.asm")):
        text = f.read_text()
        name = re.search(r"db\s+(\w+)\s*;\s*\d+", text).group(1)
        if name not in species:
            continue
        stats = [int(x) for x in re.search(r"db\s+(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)", text).groups()]
        t1, t2 = re.search(r"db\s+(\w+),\s*(\w+)\s*;\s*type", text).groups()
        base[species[name]] = (tuple(stats), (types[t1], types[t2]))

    catch_items = {}
    for m in re.finditer(r"db\s+(\S+),\s*(\w+)", (root / "data/items/catch_rate_items.asm").read_text()):
        key = m.group(1)
        rate = 0xFF if key == "-1" else items[key]
        catch_items[rate] = items[m.group(2)]

    charmap = {}
    english = (root / "constants/charmap.asm").read_text().split("; Japanese control characters", 1)[0]
    for m in re.finditer(r'charmap "(.)",\s*\$([0-9a-fA-F]{2})', english):
        charmap.setdefault(m.group(1), int(m.group(2), 16))

    lines = [
        '"""Game Boy Pokemon data, generated by scripts/gen_gb_tables.py from pret/pokecrystal. Do not edit."""',
        "",
        "# Gen 1 internal species index (1-based position) -> national dex number; 0 = no Pokemon.",
        f"GEN1_INDEX_TO_DEX = {[0] + gen1_order!r}",
        "",
        "# National dex 1-151 -> base Special in Red/Blue (index 0 unused).",
        f"KANTO_SPECIAL = {[0] + specials!r}",
        "",
        "# National dex -> ((hp, atk, def, spd, spatk, spdef), (type1, type2)) in Gold/Silver/Crystal.",
        "GEN2_BASE = {",
        *[f"    {dex}: ({stats!r}, {t!r})," for dex, (stats, t) in sorted(base.items())],
        "}",
        "",
        "# Type constants (shared by Gen 1 and Gen 2; Steel and Dark are Gen 2 only).",
        f"TYPES = {dict(sorted(((k, v) for k, v in types.items() if k.isupper() and v < 0x20), key=lambda kv: kv[1]))!r}",
        "",
        "# Time Capsule: a Gen 1 catch rate a Gen 2 game turns into this item instead of the same-numbered item.",
        f"CATCH_RATE_ITEMS = {catch_items!r}",
        "",
        "# National dex -> pret constant name.",
        f"SPECIES_NAMES = {dict(sorted(by_value.items()))!r}",
        "",
        "# Character -> Game Boy text byte (English games).",
        f"CHARMAP = {charmap!r}",
        "",
    ]
    out.write_text("\n".join(lines))
    print(f"wrote {out}: {len(gen1_order)} Gen 1 indexes, {len(specials)} specials, {len(base)} base stats")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]), Path(__file__).resolve().parents[1] / "pokeuds/vc/gbdata.py")
